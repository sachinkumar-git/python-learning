#  for loop

fruits = ["apple", 'banana', "cherry", "date", "elderberry"]

for fruit in fruits :
    print (fruit)


name =  "sacjin kumar"

for ch in name :
    print(ch, end=" ") # for same line 


#  range first version 
print ("range first version")
for i in range(5):
    print (i)

print ("range second version")
for i in range (2,7):
    print(i)

print ("range third version")
for i in range (2,10,2):
    print (i)


# reverse order 
print ("reverse order ")
for i in range(10,0,-1) :
    print (i)